/// «Зал славы»: спортсмены Казахстана. Тексты и фото предоставлены
/// автором проекта.
class SeedAthlete {
  const SeedAthlete({
    required this.name,
    required this.headline,
    required this.sport,
    this.catalogSport,
    this.year,
    required this.story,
    required this.photos,
  });

  /// Имя спортсмена — заголовок карточки.
  final String name;

  /// Главное достижение одной строкой — под именем.
  final String headline;

  /// Вид спорта как на табличке.
  final String sport;

  /// Вид спорта каталога для похожих товаров (null — в каталоге нет).
  final String? catalogSport;
  final String? year;
  final String story;

  /// Ключи фото: assets/images/exhibits/kz_<ключ>.jpg. Первое — обложка,
  /// остальные листаются на странице экспоната.
  final List<String> photos;

  static const String imagesFolder = 'assets/images/exhibits';

  List<String> get imagePaths =>
      [for (final String photo in photos) '$imagesFolder/kz_$photo.jpg'];
}

